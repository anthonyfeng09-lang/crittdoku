const TABLE: Record<string, Dict> = { en: EN, es: ES, fr: FR, zh: ZH, ar: AR };

export type TKey = keyof typeof EN;

/** returns a lookup fn; unknown keys and langs fall back to English */
export function translator(lang: string) {
  const d = TABLE[lang] ?? EN;
  return (key: TKey, vars?: Record<string, string | number>): string => {
    let s = d[key] ?? EN[key] ?? String(key);
    if (vars)
      for (const [k, v] of Object.entries(vars))
        s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    return s;
  };
}

export type T = ReturnType<typeof translator>;

